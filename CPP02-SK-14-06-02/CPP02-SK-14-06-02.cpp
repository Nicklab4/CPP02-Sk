// Что оценивается
// Корректный ход игры, соответствующий правилам.
// Правильный (желательно красивый) вывод игрового поля.
// Понятный игроку интерфейс.

#include <iostream>
#include <vector>

void print(char places[3][3])
{
    int y = 1;
    std::cout << "  1   2   3\n";
    for (int i = 0; i < 7; i++)
    {
        for (int j = 0; j < 7; j++)
        {
            if (!(i % 2))
            {
                if (j == 6)
                    std::cout << "*";
                else
                    std::cout << "**";
            }
            else if (!(j % 2))
                std::cout << "*";
            else
                std::cout << " " << places[i / 2][j / 2] << " ";
        }
        if (i % 2)
        {
            std::cout << " " << y;
            y++;
        }
        std::cout << "\n";
    }
}

bool check(char places[3][3], bool spaces[3][3])
{
    for (int i = 0; i < 3; i++)
    {
        if ((spaces[i][0] == true &&
             spaces[i][0] == spaces[i][1] && spaces[i][1] == spaces[i][2] &&
             places[i][0] == places[i][1] && places[i][1] == places[i][2])
              ||
            (spaces[0][i] == true &&
             spaces[0][i] == spaces[1][i] && spaces[1][i] == spaces[2][i] &&
             places[0][i] == places[1][i] && places[1][i] == places[2][i]))
            return true;
    }
    return false;
}

int main()
{
    char places[3][3]{{' ', ' ', ' '}, {' ', ' ', ' '}, {' ', ' ', ' '}};
    bool spaces[3][3]{{0, 0, 0}, {0, 0, 0}, {0, 0, 0}};
    char gamer_name = 'X';
    int count = 1;
    int x, y;

    while (count <= 9)
    {
        std::cout << "Ход игрока " << gamer_name << "\n";
        std::cout << "Введите координаты X и Y: \n";
        std::cin >> x >> y;

        x--;
        y--;

        if (x < 0 && x > 2)
        {
            std::cout << "Ошибка! X должен быть в пределах от 1 до 3.\n";
            continue;
        }

        if (y < 0 && y > 2)
        {
            std::cout << "Ошибка! Y должен быть в пределах от 1 до 3.\n";
            continue;
        }

        if (spaces[y][x] == true)
        {
            std::cout << "Ошибка! Эта клетка уже занята.\n";
            continue;
        }
        else
        {
            spaces[y][x] = true;
            count++;
            places[y][x] = gamer_name;

            print(places);

            if (check(places, spaces))
            {
                std::cout << "\nПоздравляем! Выиграл игрок - " << gamer_name << "\n";
                break;
            }

            if (gamer_name == 'X')
                gamer_name = 'O';
            else
                gamer_name = 'X';
        }

        if (count == 9)
            std::cout << "Ничья!\n";
    }
}