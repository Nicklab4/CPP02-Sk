// Не забывайте про случай ничьей.
// Как и в предыдущем задании, здесь будет удобно сразу заполнить массив значениями
// false. Количество мест, доступных для заполнения, заранее известно. В процессе
// заполнения из этой переменой нужно не забывать вычитать единицу. Чтобы отметить
// место как занятое, нужно лишь написать places[i][j] = true;.
// Проверку на победу игрока, которую надо осуществлять после каждого хода, можно
// сделать с помощью вложенного цикла, сразу проверяя и вертикаль, и горизонталь, а как
// именно — попробуйте догадаться сами.
// Здесь заранее известно число ходов — 3 * 3. Столько раз должен быть выполнен цикл,
// который спрашивает у очередного игрока координаты.
// Символ, который будет установлен в указанных координатах, можно на каждом шаге
